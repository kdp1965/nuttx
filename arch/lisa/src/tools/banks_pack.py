#!/usr/bin/env python3
"""banks_pack.py - a bank map for the NuttX LISA build from the sizes of its
objects: every source packed into 32 KB code banks (first fit, decreasing),
arch and boards in the common area.  Reads the .rel files (A BANKn/CODE size)
and the .asm beside each (the source file name), writes the map on stdout.

--keep <old map>: one map for several configurations - the sources built
now are packed from their sizes, and the old map's sources this build did
not compile (another configuration's) keep their old groups, each group in
a bank of its own after the packed ones (a group only lost members, so it
still fits)."""
import os, re, sys, collections
roots = ["/Users/Ken2/projects/lisa/nuttx", "/Users/Ken2/projects/lisa/nuttx-apps"]
LIMIT = int(os.environ.get("BANK_LIMIT", "31000"))
keep = None
if len(sys.argv) > 2 and sys.argv[1] == "--keep":
    keep = sys.argv[2]
FIRST = 2
files = []
for root in roots:
    base = os.path.dirname(root)
    for dp, dn, fn in os.walk(root):
        if "/.git" in dp: continue
        for f in fn:
            if not f.endswith(".rel"): continue
            path = os.path.join(dp, f); size = 0
            for line in open(path, errors="replace"):
                m = re.match(r"A (BANK\d+|CODE) size ([0-9A-Fa-f]+)", line)
                if m: size += int(m.group(2), 16)
            if size == 0: continue
            asm = path[:-4] + ".asm"; src = None
            if os.path.exists(asm):
                for line in open(asm, errors="replace"):
                    m = re.match(r";\s*(\S+\.c):", line)
                    if m: src = m.group(1); break
            if not src: continue
            # the source's path: beside the object, or beside the object's bin/
            cands = [os.path.join(dp, src), os.path.join(os.path.dirname(dp), src) if os.path.basename(dp) == "bin" else None]
            srcpath = next((c for c in cands if c and os.path.exists(c)), None)
            if not srcpath: print("? no source for", path, src, file=sys.stderr); continue
            rel = "/" + os.path.relpath(os.path.realpath(srcpath), os.path.realpath(base))
            if "/nuttx/arch/" in rel or "/nuttx/boards/" in rel: continue
            files.append((rel, size))
files.sort(key=lambda x: -x[1])
banks = []  # [used, [(rel,size)...]]
for rel, size in files:
    for b in banks:
        if b[0] + size <= LIMIT: b[0] += size; b[1].append((rel, size)); break
    else:
        banks.append([size, [(rel, size)]])
kept = []   # [(old bank, [rel ...])] for the old map's sources not built now
if keep:
    built = set(rel for rel, size in files)
    groups = {}
    for line in open(keep):
        f = line.split()
        if len(f) != 2 or line.startswith("#") or not f[1].isdigit(): continue
        rel, bank = f[0], int(f[1])
        if rel.endswith("/") or bank == 0 or rel in built: continue
        groups.setdefault(bank, []).append(rel)
    kept = sorted(groups.items())
print("# The code bank of each source (arch/lisa/src/tools/lisa-sdcc): a line is a")
print("# shell pattern matched against the source's real path and a bank, the first")
print("# match wins; bank 0 and no match are the common area below word 0x4000")
print("# (where the vectors, the interrupt entry, the context switch, the constants")
print("# and the initializers must be).  Generated by banks_pack.py from the object")
print("# sizes of a build (first fit into %d bytes of the 32768 of a bank); a file" % LIMIT)
print("# not listed goes to the last banks.  %d files, %d banks." % (len(files), len(banks)))
if kept:
    print("# Kept from %s (sources another configuration builds): %d files in %d banks." %
          (os.path.basename(keep), sum(len(g) for b, g in kept), len(kept)))
print("/nuttx/arch/                0")
print("/nuttx/boards/              0")
for i, b in enumerate(banks):
    print("# bank %d: %d bytes" % (FIRST + i, b[0]))
    for rel, size in sorted(b[1]):
        print("%-48s %d" % (rel, FIRST + i))
nb = FIRST + len(banks)
for old, group in kept:
    print("# bank %d: kept (bank %d before)" % (nb, old))
    for rel in sorted(group):
        print("%-48s %d" % (rel, nb))
    nb += 1
print("# anything else")
print("/nuttx-apps/                %d" % nb)
print("/nuttx/                     %d" % (nb + 1))
